import { randomUUID } from 'node:crypto';
import fs from 'node:fs/promises';
import { logger } from '../config/logger.js';
import { prisma } from '../config/prisma.js';
import { activityRepository } from '../repositories/activity.repository.js';
import { fileRepository } from '../repositories/file.repository.js';
import { storage } from '../storage/index.js';
import { AppError } from '../utils/AppError.js';
import { detectFileType } from '../utils/detectFileType.js';
import { itemName } from '../validators/common.validators.js';
import { assertFolderOwned } from './folder.service.js';

/** Deletes Multer's temp files. Safe to call twice (force: no error if already gone). */
export function removeTempFiles(files = []) {
  return Promise.all(files.map((file) => fs.rm(file.path, { force: true })));
}

/**
 * The browser's filename → a safe display name. Some browsers send a full path
 * ("C:\Users\me\photo.png"), so only the last part is kept. NFC normalisation makes
 * "é" typed on a Mac and on Windows the same characters.
 */
function displayName(originalname) {
  const base = String(originalname ?? '')
    .split(/[/\\]/)
    .pop()
    .normalize('NFC');
  const result = itemName.safeParse(base);
  if (!result.success) {
    throw new AppError(400, 'INVALID_FILE_NAME', result.error.issues[0].message);
  }
  return result.data;
}

/**
 * Stores ONE uploaded temp file. Status machine: UPLOADING → ACTIVE (or FAILED).
 *
 * If the server crashes half-way, the row stays UPLOADING with its quota reserved; the
 * cleanup job (B5) finds such rows and repairs them, so nothing leaks permanently.
 */
async function storeOne(userId, folderId, file) {
  const name = displayName(file.originalname);

  const type = await detectFileType(file.path, name);
  if (!type) {
    throw new AppError(415, 'UNSUPPORTED_FILE_TYPE', 'This file type is not supported.');
  }

  const id = randomUUID();
  // The key is generated by us, never derived from the user's filename.
  const storageKey = `users/${userId}/${id}`;
  const sizeBytes = BigInt(file.size);

  // Reservation + row together: if creating the row fails, the reservation is undone.
  await prisma.$transaction(async (tx) => {
    if (!(await fileRepository.reserveQuota(userId, sizeBytes, tx))) {
      throw new AppError(413, 'QUOTA_EXCEEDED', 'Not enough storage space for this file.');
    }
    await fileRepository.create(
      {
        id,
        userId,
        folderId,
        originalName: name,
        storageKey,
        mimeType: type.mimeType,
        category: type.category,
        sizeBytes,
        status: 'UPLOADING',
      },
      tx,
    );
  });

  try {
    await storage.upload({ key: storageKey, sourcePath: file.path, contentType: type.mimeType });
  } catch (err) {
    logger.error({ err, fileId: id }, 'Storing an uploaded file failed');
    // Roll back: mark FAILED and give the reserved space back, together.
    await prisma.$transaction([
      fileRepository.setStatus(id, 'FAILED'),
      fileRepository.releaseQuota(userId, sizeBytes),
    ]);
    await storage.delete(storageKey).catch(() => {}); // best effort; the job retries
    throw new AppError(500, 'UPLOAD_FAILED', 'The file could not be saved. Please try again.');
  }

  return prisma.$transaction(async (tx) => {
    const stored = await fileRepository.setStatus(id, 'ACTIVE', tx);
    await activityRepository.record(
      {
        userId,
        action: 'FILE_UPLOADED',
        targetType: 'FILE',
        targetId: id,
        metadata: { name, size: file.size },
      },
      tx,
    );
    return stored;
  });
}

export const uploadService = {
  /**
   * Stores each file independently, so one bad file doesn't fail the whole batch.
   * Returns { uploaded: File[], failed: [{ name, error }] }.
   */
  async uploadFiles(userId, { folderId = null }, files) {
    if (files.length === 0) {
      throw new AppError(400, 'NO_FILES', 'Choose at least one file to upload.');
    }
    // A wrong or foreign folder fails the whole request (404).
    await assertFolderOwned(userId, folderId);

    const uploaded = [];
    const failed = [];
    // One at a time: keeps disk and database load predictable, and makes quota
    // decisions in a clear order (file 1 first, then file 2...).
    for (const file of files) {
      try {
        uploaded.push(await storeOne(userId, folderId, file));
      } catch (err) {
        const error =
          err instanceof AppError
            ? err
            : new AppError(500, 'UPLOAD_FAILED', 'The file could not be saved. Please try again.');
        if (!(err instanceof AppError)) logger.error({ err }, 'Unexpected upload error');
        failed.push({ name: file.originalname, error });
      } finally {
        await fs.rm(file.path, { force: true });
      }
    }
    return { uploaded, failed };
  },
};
